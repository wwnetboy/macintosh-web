export const languages = [
  { code: 'zh-CN', label: '简体中文' },
  { code: 'en', label: 'English' },
]

const storageKey = 'macintosh-language'
let language = 'zh-CN'
try {
  const saved = localStorage.getItem(storageKey)
  if (languages.some(({ code }) => code === saved)) language = saved
} catch {
  // Language selection also works when browser storage is unavailable.
}

export function getLanguage() {
  return language
}

export function setLanguage(code) {
  if (!languages.some((item) => item.code === code) || code === language) return
  language = code
  try {
    localStorage.setItem(storageKey, code)
  } catch {
    // Keep the selected language for this visit.
  }
}

export function t(source = '', values = {}) {
  const message = language === 'en' ? english[source] ?? source : source
  return String(message).replace(/\{(\w+)\}/g, (match, key) => values[key] ?? match)
}

export function translateDOM(root, values = {}) {
  root.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = t(element.dataset.i18n, values)
  })
  root.querySelectorAll('[data-i18n-label]').forEach((element) => {
    element.setAttribute('aria-label', t(element.dataset.i18nLabel, values))
  })
}
